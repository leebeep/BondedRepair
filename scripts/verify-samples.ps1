# Service-fee line: materialCd = repaired goods code; desc = name + (已修复) + 维修服务费
# NOTE: expected Chinese values are compared via base64 to avoid console encoding issues.

$ErrorActionPreference = 'Stop'
$sql = @'
select concat('epd_name|', to_base64(int_product_name)) from epd101_data where int_product_no='BAT-M01' and execute_type='1' limit 1;
select concat('epd_ver|', version) from epd101_data where int_product_no='BAT-M01' and execute_type='1' limit 1;
select concat('epd_gmodel|', to_base64(g_model)) from epd101_data where int_product_no='BAT-M01' and execute_type='1' limit 1;
select concat('pto_desc|', to_base64(material_desc)) from pto2_data where take_order_cd='IN-M2-01' and material_cd='BAT-M01' limit 1;
select concat('pto_cnt|', storage_cnt) from pto2_data where take_order_cd='IN-M2-01' and material_cd='BAT-M01' limit 1;
select concat('pto_spec|', to_base64(specifications_models)) from pto2_data where take_order_cd='IN-M2-01' and material_cd='BAT-M01' limit 1;
select concat('pto_formnum|', to_base64(busi_form_num)) from pto2_data where take_order_cd='IN-M2-01' and material_cd='BAT-M01' limit 1;
select concat('pto_unit1|', unit1_num) from pto2_data where take_order_cd='IN-M2-01' and material_cd='BAT-M01' limit 1;
select concat('rrd_qty|', issue_material_qty) from rrd2_data where finish_material_num='IS-M2-01' and material_cd='BAT-M01' limit 1;
select concat('rrd_workno|', to_base64(work_no)) from rrd2_data where finish_material_num='IS-M2-01' and material_cd='BAT-M01' limit 1;
select concat('mso_fee_cd|', to_base64(material_cd)) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('mso_fee_desc|', to_base64(material_desc)) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('mso_fee_num|', material_num) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('mso_fee_ver|', material_version) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('mso_fee_bonded|', is_bonded) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('mso_fee_unit|', to_base64(calc_unit)) from mso2_data where return_material_no='RC-M2-01' and return_type='8' limit 1;
select concat('sdo_fee_cd|', to_base64(material_cd)) from sdo2_data where releaseno='OUT-M3-01' and delivery_cnt=0.1 limit 1;
select concat('sdo_fee_desc|', to_base64(material_desc)) from sdo2_data where releaseno='OUT-M3-01' and delivery_cnt=0.1 limit 1;
select concat('sdo_fee_busidesc|', to_base64(busi_desc)) from sdo2_data where releaseno='OUT-M3-01' and delivery_cnt=0.1 limit 1;
select concat('sdo_rows|', count(*)) from sdo2_data where releaseno='OUT-M3-01';
select concat('sdo_busitype|', busi_type) from sdo2_data where releaseno='OUT-M3-01' limit 1;
select concat('receipts_pending|', count(*)) from br_declare_log where sync_flag='0';
'@

$tmp = "$env:TEMP\verify_samples.sql"
$sql | Out-File $tmp -Encoding ascii
docker cp $tmp br-mysql:/tmp/verify.sql
$out = docker exec br-mysql sh -c "mysql --default-character-set=utf8mb4 -uroot -pbr_root_2026 bonded_repair -N < /tmp/verify.sql 2>/dev/null"

$kv = @{}
foreach ($line in $out) {
    $p = $line -split '\|', 2
    if ($p.Count -eq 2) { $kv[$p[0]] = $p[1] }
}

function B64($s) { if ($s) { [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($s)) } else { $null } }
# expected base64 values (UTF-8), generated by scripts/_gen_b64.py to avoid encoding issues
$exp = @{
    epd_name         = '5paw6IO95rqQ5Yqo5Yqb55S15rGg5qih57uE77yI5b6F5L+u5aSN77yJ'
    epd_gmodel       = 'Q1RQLTEwMEFo'
    pto_desc         = '5paw6IO95rqQ5Yqo5Yqb55S15rGg5qih57uE77yI5b6F5L+u5aSN77yJ'
    pto_spec         = 'Q1RQLTEwMEFo'
    pto_formnum      = 'UE8tMjAyNi0wMDE='
    rrd_workno       = 'V08tMjAyNi0wMDE='
    mso_fee_cd       = 'QkFULU0wMQ=='
    mso_fee_desc     = '5paw6IO95rqQ5Yqo5Yqb55S15rGg5qih57uE77yI5bey5L+u5aSN77yJ57u05L+u5pyN5Yqh6LS5'
    mso_fee_unit     = 'MDA0'
    sdo_fee_cd       = 'QkFULU0wMQ=='
    sdo_fee_desc     = '5paw6IO95rqQ5Yqo5Yqb55S15rGg5qih57uE77yI5bey5L+u5aSN77yJ57u05L+u5pyN5Yqh6LS5'
    sdo_fee_busidesc = 'c2VydmljZSBmZWU='
}
$labels = @{
    epd_name='EPD101 product name with mark suffix'; epd_ver='EPD101 version'; epd_gmodel='EPD101 g_model'
    pto_desc='PTO2 material_desc with mark suffix'; pto_cnt='PTO2 storage_cnt'; pto_spec='PTO2 specifications (required)'
    pto_formnum='PTO2 busi_form_num'; pto_unit1='PTO2 unit1_num (bonded required)'; rrd_qty='RRD2 issue qty'
    rrd_workno='RRD2 work_no'; mso_fee_cd='MSO2 fee line materialCd = repaired code (sample 00 note2)'
    mso_fee_desc='MSO2 fee line desc'; mso_fee_num='MSO2 fee line qty = 0.1'; mso_fee_ver='MSO2 fee line version'
    mso_fee_bonded='MSO2 fee line is_bonded'; mso_fee_unit='MSO2 fee line calc_unit'
    sdo_fee_cd='SDO2 fee line materialCd = repaired code'; sdo_fee_desc='SDO2 fee line desc'
    sdo_fee_busidesc='SDO2 busi_desc'; sdo_rows='SDO2 row count (incl fee line)'
    sdo_busitype='SDO2 busi_type=05'; receipts_pending='all receipts synced'
}

$fail = 0
foreach ($k in $exp.Keys) {
    $actual = $kv[$k]
    if ($actual -ne $exp[$k]) { Write-Host "FAIL  $k : expected(64) [$($exp[$k])] actual(64) [$actual]  [$($labels[$k])]" -ForegroundColor Red; $fail++ }
    else { Write-Host "PASS  $k = $(B64 $actual)  [$($labels[$k])]" -ForegroundColor Green }
}
$plain = @(
    @{ k='epd_ver'; v='1' }, @{ k='pto_cnt'; v='120.000000' }, @{ k='pto_unit1'; v='120.00000' },
    @{ k='rrd_qty'; v='120.000000' }, @{ k='mso_fee_num'; v='0.100000' }, @{ k='mso_fee_ver'; v='1.000000' },
    @{ k='mso_fee_bonded'; v='1' }, @{ k='sdo_rows'; v='3' }, @{ k='sdo_busitype'; v='05' },
    @{ k='receipts_pending'; v='0' }
)
foreach ($c in $plain) {
    $actual = $kv[$c.k]
    if ($actual -ne $c.v) { Write-Host "FAIL  $($c.k): expected [$($c.v)] actual [$actual]  [$($labels[$c.k])]" -ForegroundColor Red; $fail++ }
    else { Write-Host "PASS  $($c.k) = $actual  [$($labels[$c.k])]" -ForegroundColor Green }
}
if ($fail -gt 0) { throw "verify-samples: $fail assertion(s) failed" }
Write-Host 'SAMPLES VERIFIED - mirror rows match sample-set field by field'
